"""Generate the translated program: build/dk_code.s (+ report).

    python gen.py [--hook 02BD ...]

generate_program() does one Z80 program (code block, dispatch table) for a z80x.Config;
generate() is the Donkey Kong main CPU.
"""
import argparse, glob, json, os, pickle, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import z80x
from z80x import Emitter, compute_liveness, TABLE_ENTRIES, NMI_TOKEN
from discover import load_rom, discover

HERE = os.path.dirname(os.path.abspath(__file__))
STE = os.path.abspath(os.path.join(HERE, ".."))


def dyn_pcs():
    dyn = set()
    for f in glob.glob(os.path.join(STE, "cover*.pkl")):
        p, io = pickle.load(open(f, "rb"))
        dyn |= p
    return dyn


def build_code(extra_roots=()):
    rom = load_rom()
    dyn = dyn_pcs()
    code, tables = discover(rom, [0, 0x66] + sorted(dyn) + list(extra_roots), known=dyn)
    return rom, code, tables, dyn


def generate_program(rom, roots, dyn, cfg, hooks=(), extra_roots=()):
    """-> (code lines, table lines, report, emitter) of one program.  roots: entry pcs;
    dyn: pcs seen executing (coverage), seeds for the discovery and known code."""
    code, tables = discover(rom, list(roots) + sorted(dyn) + list(extra_roots), known=dyn,
                            rst28_tables=cfg.rst28_tables, hl_tables=cfg.hl_tables)
    live_in, live_out = compute_liveness(code)
    em = Emitter(code, live_in, live_out, cfg=cfg)
    em.hooks = set(hooks)
    # where the flags in the CCR are unknown: entries, return points, targets of computed
    # jumps (the jump tables, any code address the program holds as a number), hooks
    joins = set(roots) | set(hooks)
    for nxt, targets in tables.values():
        joins |= set(targets)
    for pc, ins in code.items():
        if ins.flow in ("call", "ccall", "rst"):
            joins.add(pc + ins.length)
        for op in ins.ops:
            if op[0] == "imm" and op[1] in code:
                joins.add(op[1])
    em.analyze(joins)
    em.live_in, em.live_out = compute_liveness(code, em.ccr_users)
    em.emit_all()
    lines = list(em.lines)
    # stubs for labels that are referenced but not translated
    missing = sorted(p for p in em.refs if p not in code)
    lines.append("; --- targets that are not code")
    for p in missing:
        lines.append("%s%04X:\tmove.w #$%04X,d7\n\tjmp z80_badpc" % (cfg.prefix, p, p))
    table = ["%s:" % cfg.table]
    row = []
    for p in range(cfg.table_entries):
        if p in code:
            row.append("%s%04X" % (cfg.prefix, p))
        elif p == cfg.nmi_token:
            row.append(cfg.token_sym)
        else:
            row.append("z80_badpc")
        if len(row) == 8:
            table.append("\tdc.l " + ",".join(row))
            row = []
    if row:
        table.append("\tdc.l " + ",".join(row))
    report = {
        "instructions": len(code),
        "unsupported": em.unsupported,
        "missing_targets": [hex(p) for p in missing],
        "tables": {hex(k): [hex(x) for x in v[1]] for k, v in tables.items()},
    }
    return lines, table, report, em


def generate(hooks=(), out=None, extra_roots=()):
    """Donkey Kong main CPU -> dk_code.s text."""
    rom = load_rom()
    dyn = dyn_pcs()
    code_lines, table, rep, em = generate_program(rom, [0, 0x66], dyn, z80x.Config(), hooks, extra_roots)
    lines = ["; generated by gen.py -- Donkey Kong main CPU, Z80 -> 68000", "\tsection text,code"]
    lines += code_lines
    lines += ["\tsection data,data", "\tcnop 0,4", "TABLE_ENTRIES = %d" % TABLE_ENTRIES]
    lines += table
    return "\n".join(lines) + "\n", rep, em


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--hook", action="append", default=[])
    ap.add_argument("-o", default=os.path.join(STE, "build", "dk_code.s"))
    a = ap.parse_args()
    text, rep, em = generate([int(h, 16) for h in a.hook])
    os.makedirs(os.path.dirname(a.o), exist_ok=True)
    open(a.o, "w").write(text)
    print("instructions:", rep["instructions"], " lines:", len(text.splitlines()))
    print("unsupported:", len(rep["unsupported"]))
    for u in rep["unsupported"][:40]:
        print("   %04X %-24s %s" % u)
    print("missing targets:", rep["missing_targets"])
