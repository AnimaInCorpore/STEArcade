"""Generate the translated program: build/dk_code.s (+ report).

    python gen.py [--hook 02BD ...]
"""
import argparse, glob, json, os, pickle, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import z80x
from z80x import Emitter, compute_liveness, TABLE_ENTRIES, NMI_TOKEN
from discover import load_rom, discover

HERE = os.path.dirname(os.path.abspath(__file__))
STE = os.path.abspath(os.path.join(HERE, ".."))


def dyn_pcs():
    dyn = set()
    for f in glob.glob(os.path.join(STE, "cover*.pkl")):
        p, io = pickle.load(open(f, "rb"))
        dyn |= p
    return dyn


def build_code(extra_roots=()):
    rom = load_rom()
    dyn = dyn_pcs()
    code, tables = discover(rom, [0, 0x66] + sorted(dyn) + list(extra_roots), known=dyn)
    return rom, code, tables, dyn


def generate(hooks=(), out=None, extra_roots=()):
    rom, code, tables, dyn = build_code(extra_roots)
    live_in, live_out = compute_liveness(code)
    em = Emitter(code, live_in, live_out)
    em.hooks = set(hooks)
    em.emit_all()
    lines = []
    lines.append("; generated by gen.py -- Donkey Kong main CPU, Z80 -> 68000")
    lines.append("\tsection text,code")
    lines += em.lines
    # stubs for labels that are referenced but not translated
    missing = sorted(p for p in em.refs if p not in code)
    lines.append("; --- targets that are not code")
    for p in missing:
        lines.append("Z%04X:\tmove.w #$%04X,d7\n\tjmp z80_badpc" % (p, p))
    lines.append("\tsection data,data")
    lines.append("\tcnop 0,4")
    lines.append("z80_dispatch:")
    row = []
    for p in range(TABLE_ENTRIES):
        if p in code:
            row.append("Z%04X" % p)
        elif p == NMI_TOKEN:
            row.append("z80_nmi_ret")
        else:
            row.append("z80_badpc")
        if len(row) == 8:
            lines.append("\tdc.l " + ",".join(row))
            row = []
    if row:
        lines.append("\tdc.l " + ",".join(row))
    text = "\n".join(lines) + "\n"
    report = {
        "instructions": len(code),
        "unsupported": em.unsupported,
        "missing_targets": [hex(p) for p in missing],
        "tables": {hex(k): [hex(x) for x in v[1]] for k, v in tables.items()},
    }
    return text, report, em


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--hook", action="append", default=[])
    ap.add_argument("-o", default=os.path.join(STE, "build", "dk_code.s"))
    a = ap.parse_args()
    text, rep, em = generate([int(h, 16) for h in a.hook])
    os.makedirs(os.path.dirname(a.o), exist_ok=True)
    open(a.o, "w").write(text)
    print("instructions:", rep["instructions"], " lines:", len(text.splitlines()))
    print("unsupported:", len(rep["unsupported"]))
    for u in rep["unsupported"][:40]:
        print("   %04X %-24s %s" % u)
    print("missing targets:", rep["missing_targets"])
