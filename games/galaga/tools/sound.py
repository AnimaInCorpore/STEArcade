"""Galaga's sound on the STE's YM2149 (src/galaga.s `snd_update` is this model in 68000 code, sound_test.py compares them).

The arcade (MAME namco/galaga.cpp, devices/sound/namco.cpp): the sound CPU (CPU3, translated, its NMI handler twice a
game frame) writes the Namco WSG at $6800-$681F: three voices, each a 32 step 4-bit waveform from the PROM prom-1.1d
(8 waveforms), a frequency (voice 0: 20 bits from $10-$14, voices 1 / 2: 16 bits from $16-$19 / $1B-$1E, the low
nibble 0), a volume ($15, $1A, $1F) and a waveform ($05, $0A, $0F).  The WSG runs at 96 kHz: a voice plays its 32
steps freq * 96000 / 2^20 times a second.  The 54XX (the player's explosion: two noise channels started by the main
CPU through the 06XX, commands $1x / $2x) is not emulated.

The YM2149 plays square waves: each voice becomes the YM channel of its number.
* Pitch: the period (2 MHz / 16 counts) 125000 / (f * h) = 1365333 / (freq * h); h is the waveform's dominant
  harmonic (wave 4 repeats its shape twice in 32 steps: an octave up), clamped to 1-4095.
* Loudness: the WSG's amplitude is volume / 15 times the waveform's RMS (a full square has 7); the YM's levels are
  logarithmic, 3 dB apart: level = 15 + 2 log2(volume / 15 * rms / 7), 0 for volume 0.
* The explosion: a noise burst on channel C (when louder than voice 2) with the envelope EXPL, started by a 54XX
  command $1x / $2x.
"""
import math
import os
import sys
sys.path[:0] = [os.path.dirname(os.path.abspath(__file__)), os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "engine")]
from machine import load

NOISE = 26                                  # the explosion's noise period (low rumble)
EXPL = [15] * 4 + [l for l in range(14, 0, -1) for _ in range(3)] + [0]     # its level per game frame
DIVIDEND = 1365333                          # 125000 * 2^20 / 96000


def waves():
    p = load("prom-1.1d")
    return [[p[w * 32 + i] & 15 for i in range(32)] for w in range(8)]


def analyse():
    """per waveform: (dominant harmonic, RMS)"""
    out = []
    for s in waves():
        m = sum(s) / 32
        amp = [abs(sum((x - m) * complex(math.cos(2 * math.pi * k * i / 32), -math.sin(2 * math.pi * k * i / 32))
                       for i, x in enumerate(s))) for k in range(1, 17)]
        h = 2 if amp[1] > 1.5 * amp[0] else 1         # (only an octave up is followed; wave 6's second harmonic is close
        out.append((h, math.sqrt(sum((x - m) ** 2 for x in s) / 32)))   # to its fundamental: it stays)
    return out


def tables():
    """(harmonic shift per waveform: 0 / 1, levels [wave * 16 + volume])"""
    shifts, levels = [], []
    for h, rms in analyse():
        shifts.append(h - 1)
        for v in range(16):
            levels.append(0 if v == 0 else max(0, min(15, round(15 + 2 * math.log2(v / 15 * rms / 7)))))
    return shifts, levels


SHIFTS, LEVELS = tables()


def voice(r, ch):
    """(period, level) of a WSG voice from the registers r (32 values, low nibbles), level 0: silent"""
    b = ch * 5
    freq = (r[0x10] & 15 if ch == 0 else 0) + ((r[b + 0x11] & 15) << 4) + ((r[b + 0x12] & 15) << 8) + \
        ((r[b + 0x13] & 15) << 12) + ((r[b + 0x14] & 15) << 16)
    vol = r[b + 0x15] & 15
    wave = r[b + 5] & 7
    if vol == 0 or freq == 0:
        return 0, 0
    if freq < 334:
        p = 4095
    elif freq > 0xFFFF:
        p = 20
    else:
        p = DIVIDEND // freq
    p = max(1, p >> SHIFTS[wave])
    return p, LEVELS[wave * 16 + vol]


def ym_image(r, expl):
    """the YM's registers 0-10 for the WSG registers r and the explosion's level expl"""
    out = [0] * 11
    mix = 0xC0 | 0x38 | 0x07
    for ch in range(3):
        p, lvl = voice(r, ch)
        if lvl:
            out[2 * ch], out[2 * ch + 1], out[8 + ch] = p & 255, p >> 8, lvl
            mix &= ~(1 << ch)
    if expl > out[10]:
        out[4] = out[5] = 0
        out[10] = expl
        mix = (mix | 4) & ~0x20                  # channel C: noise, no tone
        out[6] = NOISE
    out[7] = mix
    return out


class Explosion:
    """the envelope's state (the 68000's snd_expl): -1 off, else the frame of EXPL"""
    def __init__(self):
        self.t = -1

    def trigger(self):
        self.t = 0

    def step(self):
        """the level of this game frame"""
        if self.t < 0:
            return 0
        lvl = EXPL[self.t]
        self.t = self.t + 1 if self.t + 1 < len(EXPL) else -1
        return lvl


def emit(path):
    lines = ["; generated by games/galaga/tools/sound.py: the WSG -> YM2149 tables (galaga.s snd_update)",
             "snd_shift:\tdc.b\t" + ",".join(str(x) for x in SHIFTS),
             "snd_level:"]
    for w in range(8):
        lines.append("\tdc.b\t" + ",".join(str(x) for x in LEVELS[w * 16:w * 16 + 16]))
    lines.append("snd_expl_env:\tdc.b\t" + ",".join(str(x) for x in EXPL))
    lines.append("SND_EXPL_LEN = %d" % len(EXPL))
    lines.append("SND_NOISE = %d" % NOISE)
    lines.append("\teven")
    open(path, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    for w, ((h, rms), s) in enumerate(zip(analyse(), waves())):
        print("wave %d %s  harmonic %d  rms %.2f  levels %s" % (w, "".join("%x" % x for x in s), h, rms, LEVELS[w * 16:w * 16 + 16]))
