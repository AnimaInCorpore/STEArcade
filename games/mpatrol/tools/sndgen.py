"""The sound board's M6803 driver (mp-s1.1a at $F000-$FFFF) translated to 68000 code with engine/m6801x.py's emitter.

    python sndgen.py   ->  build/mpatrol/snd_code.s

What the STE runs (sound.TickBoard is the same in Python): the reset ($FB00) once, then per arcade frame one
iteration of the main loop ($FB1B .. `jmp $FB1B`, which returns to the runtime: mcu_restart) for each command ($BC =
command & $1F) and one for each of the frame's ticks ($C0 = 1).  sound.SKIP leaves out the busy waits and the loop's
port B write; the NMI handler (the ADPCM voice: the STE plays it as samples, src/sound.s) and the IRQ handler (the
runtime sets $BC) are not translated.  The ports: P1 / P2 writes call mcu_wr_p1 / mcu_wr_p2 (the AY bus), a P1 read
mcu_rd_p1 (an AY register; port A of 45M: the command).  As Kung-Fu Master's tools/sndgen.py (its SndEmitter: words
at odd addresses as byte pairs).
"""
from pathlib import Path
import sys
sys.path[:0] = [str(Path(__file__).resolve().parent), str(Path(__file__).resolve().parents[3] / 'engine')]
from m6801dis import discover
from m6801x import MCUEmitter, liveness, Unsupported
from paths import build_dir
import sound

BASE = 0xF000
NMI = range(0xFBD9, 0xFC48)              # (the NMI handler)
IRQ = range(0xFC8B, 0xFC98)              # (the IRQ handler)


class SndEmitter(MCUEmitter):
    """m6801x's emitter with 16-bit accesses at odd or indexed addresses as byte pairs (the driver keeps words at odd
    RAM addresses: $CD, $CF, $D1; the 68000 faults on an odd word access), and the reset's `stx $00` (both DDRs)"""

    def odd_static(self, ins):
        return ins.mode in ('dir', 'ext') and ins.arg & 1 and not self.is_io(ins)

    def byte_eas(self, ins):
        if ins.mode == 'idx':
            a = ins.arg
            if a <= 126:
                return '%d(a6,d2.l)' % a, '%d(a6,d2.l)' % (a + 1)
            self.e('lea %d(a6),a0' % a)
            return '(a0,d2.l)', '1(a0,d2.l)'
        a = ins.arg
        if a < 0x100:
            return '$%X(a6)' % a, '$%X(a6)' % (a + 1)
        return 'mcu_mem+$%04X' % a, 'mcu_mem+$%04X' % (a + 1)

    def word_src(self, ins):
        if self.odd_static(ins):
            hi, lo = self.byte_eas(ins)
            self.e('moveq #0,d3')
            self.e('move.b %s,d3' % hi)
            self.e('lsl.w #8,d3')
            self.e('move.b %s,d3' % lo)
            return 'd3'
        return super().word_src(ins)

    def emit(self, ins):
        if ins.mn == 'stx' and ins.mode == 'dir' and ins.arg == 0:
            def b():                              # (the DDRs: plain registers here; a P1 read ignores them)
                self.e('move.b d2,1(a6)')
                self.e('ror.w #8,d2')
                self.e('move.b d2,(a6)')
                self.e('ror.w #8,d2')
                self.e('tst.w d2')
            self.wrap(ins.pc, 8 | 4 | 2, b)
            return
        if ins.mn in ('stx', 'std') and (ins.mode == 'idx' or self.odd_static(ins)):
            def b():
                hi, lo = self.byte_eas(ins)
                if ins.mn == 'stx':
                    self.e('move.w d2,d7')
                else:
                    self.e('move.b d0,d7')
                    self.e('lsl.w #8,d7')
                    self.e('move.b d1,d7')
                self.e('move.b d7,%s' % lo)
                self.e('ror.w #8,d7')
                self.e('move.b d7,%s' % hi)
                self.e('ror.w #8,d7')
                self.e('tst.w d7')
            self.wrap(ins.pc, 8 | 4 | 2, b)       # (N Z V)
            return
        if ins.mn == 'sts' and (ins.mode == 'idx' or self.odd_static(ins)):
            raise Unsupported('sts at an odd address: ' + ins.text)
        super().emit(ins)


def generate():
    img = sound.rom_image()
    rom = bytes(img[0x7000:])
    entry = img[0x7FFE] << 8 | img[0x7FFF]
    code, ij = discover(rom, [entry, sound.LOOP], base=BASE, stop={sound.LOOP})
    if ij:
        raise Unsupported('indirect flow at %s' % ij)
    code = {pc: ins for pc, ins in code.items() if pc not in NMI and pc not in IRQ}
    live_in, live_out = liveness(code, [entry, sound.LOOP])
    em = SndEmitter(code, live_out, sound.SKIP, {sound.LOOP})
    em.emit_all()
    missing = sorted(p for p in em.refs if p not in code)
    if missing:
        raise RuntimeError('targets not translated: %s' % ['%04X' % p for p in missing])
    lines = ['; generated by games/mpatrol/tools/sndgen.py: the sound board\'s M6803 driver -> 68000 (m6801x)',
             '\tsection text,code'] + em.lines
    return '\n'.join(lines) + '\n', em, code


if __name__ == '__main__':
    text, em, code = generate()
    (build_dir('mpatrol') / 'snd_code.s').write_text(text)
    print('%d instructions, %d wrapped' % (len(code), em.stats['wrapped']))
