"""Convert the MAME sound board recordings to STE DMA sound: 8 bit signed mono at 6258 Hz (after games/dkongjr/tools/
sound_convert.py).

    python sound_convert.py [--rate 6258]     -> build/mario/mario_sound.bin, mario_sound.s, sound/pcm/*.wav

Input: build/mario/sound/*.wav from sound_capture.py --all (48 kHz).
  tunes    the values the game writes to $7E00 (3 frames, then 0): 1-6, 9, $0A, $20-$26 (recorded as shot_NN: the
           MCU plays each to its end; the later of two commands wins)
  effects  the rising edges of $7F00 (death, held 48 frames), $7F01 (get coin), $7F03-$7F06 (the crab, turtle, fly and
           coin latch bits) and $7F07 (skid); recorded as pin_XXXX.  $7F02 (ice) and the walk pulses $7C00 / $7C80 are
           silent in MAME's netlist (below the capture's noise floor) and are not played.
The signal is low-passed at 0.45 * rate; one scale for all clips keeps the board's relative levels.
"""
import argparse, json, os, sys, wave
import numpy as np
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "engine"))
from paths import build_dir
from sound_capture import spans

BUILD = build_dir("mario")
SRC = BUILD / "sound"
TUNES = [1, 2, 3, 4, 5, 6, 9, 10] + list(range(0x20, 0x27))
FX = {0: "pin_7f00", 1: "pin_7f01", 3: "pin_7f03", 4: "pin_7f04", 5: "pin_7f05", 6: "pin_7f06", 7: "pin_7f07"}


def load(name):
    w = wave.open(str(SRC / (name + ".wav")))
    r = w.getframerate()
    return np.frombuffer(w.readframes(w.getnframes()), np.int16).astype(np.float64) / 32768.0, r


def lowpass(x, r, cut):
    from scipy.signal import firwin, filtfilt
    return filtfilt(firwin(511, cut, fs=r), [1.0], x)


def ensure():
    """For build.py: mario_sound.s / .bin, recorded (MAME) and converted only when missing."""
    if not ((BUILD / "mario_sound.s").exists() and (BUILD / "mario_sound.bin").exists()):
        if not (SRC / "pin_7f00.wav").exists():
            import sound_capture
            sound_capture.capture_all()
        build()


def build(rate=6258, verbose=False):
    from scipy.interpolate import CubicSpline
    clips = {}
    report = {}

    def prep(name):
        x, r = load(name)
        y = lowpass(x, r, 0.45 * rate)
        end = spans(x, r)[-1][1] + 0.03
        sp = CubicSpline(np.arange(len(y)), y)
        n = int(end * rate)
        return sp(r / rate * np.arange(n)), end

    for v in TUNES:
        c, end = prep("shot_%02d" % v)
        clips["tune_%02x" % v] = c
        report["tune_%02x" % v] = dict(length_s=round(end, 3))
    for n, src in FX.items():
        c, end = prep(src)
        clips["fx_%d" % n] = c
        report["fx_%d" % n] = dict(length_s=round(end, 3))
    peak = max(np.abs(c).max() for c in clips.values())
    scale = 127.0 / peak
    pcm_dir = SRC / "pcm"
    pcm_dir.mkdir(parents=True, exist_ok=True)
    blob = bytearray()
    offs = {}
    for name, c in clips.items():
        f = min(len(c), int(0.004 * rate))                # 4 ms fade out, then an even length (DMA works on words)
        c = c.copy()
        c[len(c) - f:] *= np.linspace(1, 0, f)
        q = np.clip(np.round(c * scale), -128, 127).astype(np.int8)
        if len(q) & 1:
            q = np.append(q, np.int8(0))
        offs[name] = (len(blob), len(blob) + len(q))
        blob += q.tobytes()
        with wave.open(str(pcm_dir / (name + ".wav")), "wb") as o:   # listening copy, 8 bit as the STE plays it
            o.setnchannels(1); o.setsampwidth(1); o.setframerate(rate)
            o.writeframes((q.astype(np.int16) + 128).astype(np.uint8).tobytes())
        report[name]["bytes"] = len(q)
    (BUILD / "mario_sound.bin").write_bytes(bytes(blob))
    lines = ["; generated by games/mario/tools/sound_convert.py: 8 bit signed PCM, %d Hz" % rate,
             "SOUND_RATE\tequ\t%d" % rate,
             "SOUND_MODE\tequ\t$%02x\t\t; $ffff8921: mono, the rate" % (0x80 | {6258: 0, 12517: 1, 25033: 2, 50066: 3}[rate]),
             "", "\tsection\tdata,data", "\teven",
             "mm_sound:\tincbin\t\"mario_sound.bin\"", "mm_sound_end:", "\teven", "",
             "; $7E00 value (0-39): start, end (mm_sound relative); 0, 0: nothing",
             "sound_tunes:"]
    for n in range(40):
        k = "tune_%02x" % n
        s, e = offs.get(k, (0, 0))
        lines.append("\tdc.l\t%d,%d\t\t; %02X" % (s, e, n))
    lines.append("; $7F00-$7F07 rising edges: start, end")
    lines.append("sound_fx:")
    for n in range(8):
        s, e = offs.get("fx_%d" % n, (0, 0))
        lines.append("\tdc.l\t%d,%d\t\t; $7F0%d" % (s, e, n))
    (BUILD / "mario_sound.s").write_text("\n".join(lines) + "\n")
    json.dump(report, open(pcm_dir / "report.json", "w"), indent=1)
    if verbose:
        for k, v in report.items():
            print("%-10s %s" % (k, "  ".join("%s %s" % kv for kv in v.items())))
    print("total %d bytes (%.1f s); scale %.1f (peak %.3f)" % (len(blob), len(blob) / rate, scale, peak))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rate", type=int, default=6258, choices=(6258, 12517, 25033, 50066))
    build(ap.parse_args().rate, verbose=True)


if __name__ == "__main__":
    main()
