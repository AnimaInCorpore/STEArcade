"""Convert the MAME sound board recordings to STE DMA sound: 8 bit signed mono at 12517 Hz (after games/mario/tools/
sound_convert.py).

    python sound_convert.py [--rate 12517]     -> build/sbasketb/sb_sound.bin, sb_sound.s, sound/pcm/*.wav

Input: build/sbasketb/sound/*.wav from sound_capture.py --all (48 kHz): `base` (no command: silent when the main CPU is
parked), cmd_NN (a command alone), say_NN (the game's 254, phrase NN, 255).
  effects  the commands the game's play sends (1-$40): the clip from the command to the end of the sound; the looping
           ones ($09 and $20 play until stopped) are cut at a period of their own (found by the signal's repeat) and
           played repeating.  Command 0 stops the clip.
  speech   the phrases $80-$AE: queued by their command, spoken by the command $FF (src/sound.s).
The recordings have a DC offset (the DAC at rest): the median is removed.  The signal is low-passed at 0.45 * rate; one
scale for all clips keeps the board's relative levels.  A clip with no sound (the board makes none for that command) is
left out.
"""
import argparse, json, os, sys, wave
import numpy as np
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "engine"))
from paths import build_dir
from sound_capture import spans, EFFECTS, PHRASES

BUILD = build_dir("sbasketb")
SRC = BUILD / "sound"
LOOPS = {0x09, 0x20}


def load(name):
    w = wave.open(str(SRC / (name + ".wav")))
    r = w.getframerate()
    x = np.frombuffer(w.readframes(w.getnframes()), np.int16).astype(np.float64) / 32768.0
    return x - np.median(x), r


def lowpass(x, r, cut):
    from scipy.signal import firwin, filtfilt
    return filtfilt(firwin(511, cut, fs=r), [1.0], x)


def loop_cut(x, r):
    """(start, length) in samples of a segment that repeats: the best match of x[a:a+w] with itself L later"""
    a, w = int(1.0 * r), int(0.2 * r)
    ref = x[a:a + w]
    best = None
    for L in range(int(0.3 * r), int(6.0 * r)):
        e = np.mean((x[a + L:a + L + w] - ref) ** 2)
        if best is None or e < best[0]:
            best = (e, L)
    return a, best[1]


def ensure():
    """For build.py: sb_sound.s / .bin, recorded (MAME) and converted only when missing."""
    if not ((BUILD / "sb_sound.s").exists() and (BUILD / "sb_sound.bin").exists()):
        if not (SRC / "cmd_03.wav").exists():
            import sound_capture
            sound_capture.capture_all()
        build()


def build(rate=12517, verbose=False):
    from scipy.interpolate import CubicSpline
    clips, loops, report = {}, {}, {}

    def prep(name, loop=False):
        x, r = load(name)
        sp = spans(x, r, thresh=0.003)
        if not sp:
            return None
        y = lowpass(x, r, 0.45 * rate)
        if loop:
            a, L = loop_cut(y, r)
            seg = y[a:a + L]
            end = (L / r)
        else:
            end = sp[-1][1] + 0.03
            seg = y[:int(end * r) + 1]
        s = CubicSpline(np.arange(len(seg)), seg)
        n = int(len(seg) / r * rate)
        return s(r / rate * np.arange(n)), end

    for c in EFFECTS:
        got = prep("cmd_%02x" % c, c in LOOPS)
        if got:
            clips["cmd_%02x" % c] = got[0]
            loops["cmd_%02x" % c] = c in LOOPS
            report["cmd_%02x" % c] = dict(length_s=round(got[1], 3), loop=c in LOOPS)
    for p in PHRASES:
        got = prep("say_%02x" % p)
        if got:
            clips["say_%02x" % p] = got[0]
            report["say_%02x" % p] = dict(length_s=round(got[1], 3))
    CAP = 0.34                       # (the loudest effects, $40 and $12, peak at 0.48 and 0.40: limited to 0.34 so the rest, 0.06-0.32,
    for k in clips:                  # is 1.4 times louder than one scale for the loudest gave; MAME's level was matched in Hatari's audio)
        pk = np.abs(clips[k]).max()
        if pk > CAP:
            clips[k] = clips[k] * (CAP / pk)
    peak = max(np.abs(c).max() for c in clips.values())
    scale = 127.0 / peak
    pcm_dir = SRC / "pcm"
    pcm_dir.mkdir(parents=True, exist_ok=True)
    blob = bytearray()
    offs = {}
    for name, c in clips.items():
        c = c.copy()
        if not loops.get(name):
            f = min(len(c), int(0.004 * rate))                # 4 ms fade out, then an even length (DMA works on words)
            c[len(c) - f:] *= np.linspace(1, 0, f)
        q = np.clip(np.round(c * scale), -128, 127).astype(np.int8)
        if len(q) & 1:
            q = np.append(q, np.int8(0))
        offs[name] = (len(blob), len(blob) + len(q))
        blob += q.tobytes()
        with wave.open(str(pcm_dir / (name + ".wav")), "wb") as o:   # listening copy, 8 bit as the STE plays it
            o.setnchannels(1); o.setsampwidth(1); o.setframerate(rate)
            o.writeframes((q.astype(np.int16) + 128).astype(np.uint8).tobytes())
        report[name]["bytes"] = len(q)
    (BUILD / "sb_sound.bin").write_bytes(bytes(blob))
    lines = ["; generated by games/sbasketb/tools/sound_convert.py: 8 bit signed PCM, %d Hz" % rate,
             "SOUND_RATE\tequ\t%d" % rate,
             "SOUND_MODE\tequ\t$%02x\t\t; $ffff8921: mono, the rate" % (0x80 | {6258: 0, 12517: 1, 25033: 2, 50066: 3}[rate]),
             "", "\tsection\tdata,data", "\teven",
             "sb_sound:\tincbin\t\"sb_sound.bin\"", "sb_sound_end:", "\teven", "",
             "; command (0-255): start, end (sb_sound relative), the DMA control (1 once, 3 repeat); 0, 0: no clip",
             "sound_cmds:"]
    for n in range(256):
        k = "cmd_%02x" % n if n < 128 else "say_%02x" % n
        s, e = offs.get(k, (0, 0))
        lines.append("\tdc.l\t%d,%d,%d\t\t; %02X" % (s, e, 3 if loops.get(k) else 1, n))
    (BUILD / "sb_sound.s").write_text("\n".join(lines) + "\n")
    json.dump(report, open(pcm_dir / "report.json", "w"), indent=1)
    if verbose:
        for k, v in report.items():
            print("%-10s %s" % (k, "  ".join("%s %s" % kv for kv in v.items())))
    print("%d clips, total %d bytes (%.1f s); scale %.1f (peak %.3f)" % (len(clips), len(blob), len(blob) / rate, scale, peak))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rate", type=int, default=12517, choices=(6258, 12517, 25033, 50066))
    build(ap.parse_args().rate, verbose=True)


if __name__ == "__main__":
    main()
