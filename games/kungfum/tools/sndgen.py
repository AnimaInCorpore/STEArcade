"""The sound board's M6803 driver (a-3h, $E000-$FFFF) translated to 68000 code with engine/m6801x.py's emitter.

    python sndgen.py   ->  build/kungfum/snd_code.s

What the STE runs (sound.TickBoard is the same in Python): the boot (F900) once, then per arcade frame one iteration of
the main loop (F922 .. `jmp $F922`, which returns to the runtime: mcu_restart) for each command (`$BC` = command &
$3F) and one for each of the frame's ticks (`$C0` = 1).  The busy waits (sound.SKIP: an AY write waits for the
NMI's count $BD, a voice's start for five NMIs) are left out; the NMI handler (the ADPCM voices: the STE plays them
as samples, src/sound.s) and the IRQ handler (the runtime sets $BC) are not translated.  The ports: P1 / P2 writes
call mcu_wr_p1 / mcu_wr_p2 (the AY bus), a P1 read mcu_rd_p1 (an AY register, port A of 45M: the command).
"""
from pathlib import Path
import sys
sys.path[:0] = [str(Path(__file__).resolve().parent), str(Path(__file__).resolve().parents[3] / 'engine')]
from m6801dis import discover
from m6801x import MCUEmitter, liveness, Unsupported
from paths import build_dir
import sound

BASE = 0xE000


class SndEmitter(MCUEmitter):
    """m6801x's emitter with 16-bit accesses at odd or indexed addresses as byte pairs: this driver keeps words at
    odd RAM addresses ($D1, $CD ...) and stores them indexed; the 68000 faults on an odd word access (Musashi does
    not: Hatari found it)"""

    def odd_static(self, ins):
        return ins.mode in ('dir', 'ext') and ins.arg & 1 and not self.is_io(ins)

    def byte_eas(self, ins):
        """(high byte's ea, low byte's ea) of a word operand"""
        if ins.mode == 'idx':
            a = ins.arg
            if a <= 126:
                return '%d(a6,d2.l)' % a, '%d(a6,d2.l)' % (a + 1)
            self.e('lea %d(a6),a0' % a)
            return '(a0,d2.l)', '1(a0,d2.l)'
        a = ins.arg
        if a < 0x100:
            return '$%X(a6)' % a, '$%X(a6)' % (a + 1)
        return 'mcu_mem+$%04X' % a, 'mcu_mem+$%04X' % (a + 1)

    def word_src(self, ins):
        if self.odd_static(ins):
            hi, lo = self.byte_eas(ins)
            self.e('moveq #0,d3')
            self.e('move.b %s,d3' % hi)
            self.e('lsl.w #8,d3')
            self.e('move.b %s,d3' % lo)
            return 'd3'
        return super().word_src(ins)

    def emit(self, ins):
        if ins.mn in ('stx', 'std') and (ins.mode == 'idx' or self.odd_static(ins)):
            def b():
                hi, lo = self.byte_eas(ins)
                if ins.mn == 'stx':
                    self.e('move.w d2,d7')
                else:
                    self.e('move.b d0,d7')
                    self.e('lsl.w #8,d7')
                    self.e('move.b d1,d7')
                self.e('move.b d7,%s' % lo)
                self.e('ror.w #8,d7')
                self.e('move.b d7,%s' % hi)
                self.e('ror.w #8,d7')
                self.e('tst.w d7')
            self.wrap(ins.pc, 8 | 4 | 2, b)       # (N Z V)
            return
        if ins.mn == 'sts' and (ins.mode == 'idx' or self.odd_static(ins)):
            raise Unsupported('sts at an odd address: ' + ins.text)
        super().emit(ins)


def generate():
    img = sound.rom_image()
    rom = bytes(img[BASE:])
    code, ij = discover(rom, [0xF900, sound.LOOP], base=BASE, stop={sound.LOOP})
    if ij:
        raise Unsupported('indirect flow at %s' % ij)
    code = {pc: ins for pc, ins in code.items() if not (0xF9D4 <= pc <= 0xFA42 or 0xFA86 <= pc <= 0xFA92)}   # (NMI, IRQ)
    live_in, live_out = liveness(code, [0xF900, sound.LOOP])
    em = SndEmitter(code, live_out, sound.SKIP, {sound.LOOP})
    em.emit_all()
    missing = sorted(p for p in em.refs if p not in code)
    if missing:
        raise RuntimeError('targets not translated: %s' % ['%04X' % p for p in missing])
    lines = ['; generated by games/kungfum/tools/sndgen.py: the sound board\'s M6803 driver -> 68000 (m6801x)',
             '\tsection text,code'] + em.lines
    return '\n'.join(lines) + '\n', em, code


if __name__ == '__main__':
    text, em, code = generate()
    (build_dir('kungfum') / 'snd_code.s').write_text(text)
    print('%d instructions, %d wrapped' % (len(code), em.stats['wrapped']))
