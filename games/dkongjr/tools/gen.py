"""Generate the translated program: build/dkongjr/dkjr_code.s (+ report).

    python gen.py [--hook 02BD ...]

generate() is the Donkey Kong Junior main CPU; the translation itself is engine/translate.py.  The configuration is
Donkey Kong's (z80x.FAST) with the 24 KB ROM: the dispatch table covers $0000-$6001, the NMI return token is $6001
(RAM, never code).
"""
import argparse, glob, os, pickle, sys
sys.path[:0] = [os.path.dirname(os.path.abspath(__file__)), os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "engine")]
import z80x
from translate import generate_program
from paths import EXTRACTED, build_dir, require_coverage

BUILD = build_dir("dkongjr")
NMI_TOKEN = 0x6001
TABLE_ENTRIES = 0x6002
SEEDS = (1, 2, 3, 4, 5, 11, 12, 13, 14, 15, 16, 21, 22, 23)
COVER = ["cover_%d.pkl" % s for s in SEEDS]


def load_rom():
    return (EXTRACTED / "dkongjr" / "cpu.rom").read_bytes()


def dyn_pcs():
    require_coverage("dkongjr", COVER)
    dyn = set()
    for f in COVER:
        p, io = pickle.load(open(BUILD / f, "rb"))
        dyn |= p
    return dyn


def config():
    # the rst $28 table at $1648 (index $6388) has 6 entries; the code after it (jr $167B ...) reads as $5E26 and $3A00,
    # which led the discovery into data ($3A00-$3B62: halt, flags it can not translate)
    return z80x.Config(nmi_token=NMI_TOKEN, table_entries=TABLE_ENTRIES, rst28_counts={0x1648: 6}, **z80x.FAST)


def generate(hooks=(), extra_roots=()):
    """Donkey Kong Junior main CPU -> dkjr_code.s text."""
    rom = load_rom()
    dyn = dyn_pcs()
    code_lines, table, rep, em = generate_program(rom, [0, 0x66], dyn, config(), hooks, extra_roots)
    lines = ["; generated by gen.py -- Donkey Kong Junior main CPU, Z80 -> 68000", "\tsection text,code"]
    lines += code_lines
    lines += ["\tsection data,data", "\tcnop 0,4", "TABLE_ENTRIES = %d" % TABLE_ENTRIES]
    lines += table
    return "\n".join(lines) + "\n", rep, em


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--hook", action="append", default=[])
    ap.add_argument("-o", default=str(BUILD / "dkjr_code.s"))
    a = ap.parse_args()
    text, rep, em = generate([int(h, 16) for h in a.hook])
    open(a.o, "w").write(text)
    print("instructions:", rep["instructions"], " lines:", len(text.splitlines()))
    print("unsupported:", len(rep["unsupported"]))
    for u in rep["unsupported"][:40]:
        print("   %04X %-24s %s" % u)
    print("missing targets:", rep["missing_targets"])
