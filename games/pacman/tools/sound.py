"""Pac-Man's sound on the STE's YM2149 (src/pacman.s `snd_update` is this model in 68000 code, sound_test.py compares
them).  Galaga's method (games/galaga/tools/sound.py: the same Namco WSG, the same register map).

The arcade (MAME pacman/pacman.cpp, devices/sound/namco.cpp pacman_sound_w): the main CPU writes the WSG at
$5040-$505F in its frame handler (the low nibble counts): three voices, each a 32 step 4-bit waveform from the PROM
82s126.1m (8 waveforms), a frequency (voice 0: 20 bits from $10-$14, voices 1 / 2: 16 bits from $16-$19 / $1B-$1E, the
low nibble 0), a volume ($15, $1A, $1F) and a waveform ($05, $0A, $0F).  The WSG runs at 96 kHz (18.432 MHz / 6 / 32):
a voice plays its 32 steps freq * 96000 / 2^20 times a second.  Latch bit 1 ($5001) enables the sound.

The YM2149 plays square waves: each voice becomes the YM channel of its number.
* Pitch: the period (2 MHz / 16 counts) 125000 / (f * h) = 1365333 / (freq * h); h is the waveform's strongest
  harmonic (Pac-Man's: 1, 1, 2, 1, 8, 16, 1, 2: wave 4 sounds three octaves up; Galaga's rule followed one octave
  only), clamped to 1-4095.
* Loudness: the WSG's amplitude is volume / 15 times the waveform's RMS (a full square has 7); the YM's levels are
  logarithmic, 3 dB apart: level = 15 + 2 log2(volume / 15 * rms / 7), 0 for volume 0.
"""
import math
import os
import sys
sys.path[:0] = [os.path.dirname(os.path.abspath(__file__)), os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "engine")]
from machine import load

DIVIDEND = 1365333                          # 125000 * 2^20 / 96000


def waves():
    p = load("82s126.1m")
    return [[p[w * 32 + i] & 15 for i in range(32)] for w in range(8)]


def analyse():
    """per waveform: (dominant harmonic, RMS)"""
    out = []
    for s in waves():
        m = sum(s) / 32
        amp = [abs(sum((x - m) * complex(math.cos(2 * math.pi * k * i / 32), -math.sin(2 * math.pi * k * i / 32))
                       for i, x in enumerate(s))) for k in range(1, 17)]
        h = 1 + max(range(16), key=lambda k: amp[k])   # (the strongest: 1, 1, 2, 1, 8, 16, 1, 2 for Pac-Man's 8)
        h = 1 << (h.bit_length() - 1)                  # (a power of two: the period shifts)
        out.append((h, math.sqrt(sum((x - m) ** 2 for x in s) / 32)))
    return out


def tables():
    """(harmonic shift per waveform: log2 of the harmonic, levels [wave * 16 + volume])"""
    shifts, levels = [], []
    for h, rms in analyse():
        shifts.append(h.bit_length() - 1)
        for v in range(16):
            levels.append(0 if v == 0 or rms == 0 else max(0, min(15, round(15 + 2 * math.log2(v / 15 * rms / 7)))))
    return shifts, levels


SHIFTS, LEVELS = tables()


def voice(r, ch):
    """(period, level) of a WSG voice from the registers r (32 values, low nibbles), level 0: silent"""
    b = ch * 5
    freq = (r[0x10] & 15 if ch == 0 else 0) + ((r[b + 0x11] & 15) << 4) + ((r[b + 0x12] & 15) << 8) + \
        ((r[b + 0x13] & 15) << 12) + ((r[b + 0x14] & 15) << 16)
    vol = r[b + 0x15] & 15
    wave = r[b + 5] & 7
    if vol == 0 or freq == 0:
        return 0, 0
    if freq < 334:
        p = 4095
    elif freq > 0xFFFF:
        p = 20
    else:
        p = DIVIDEND // freq
    p = max(1, p >> SHIFTS[wave])
    return p, LEVELS[wave * 16 + vol]


def ym_image(r, enable=1):
    """the YM's registers 0-10 for the WSG registers r and the sound enable (latch bit 1)"""
    out = [0] * 11
    mix = 0xC0 | 0x38 | 0x07
    if enable:
        for ch in range(3):
            p, lvl = voice(r, ch)
            if lvl:
                out[2 * ch], out[2 * ch + 1], out[8 + ch] = p & 255, p >> 8, lvl
                mix &= ~(1 << ch)
    out[7] = mix
    return out


def emit(path):
    lines = ["; generated by games/pacman/tools/sound.py: the WSG -> YM2149 tables (pacman.s snd_update)",
             "snd_shift:\tdc.b\t" + ",".join(str(x) for x in SHIFTS),
             "snd_level:"]
    for w in range(8):
        lines.append("\tdc.b\t" + ",".join(str(x) for x in LEVELS[w * 16:w * 16 + 16]))
    lines.append("\teven")
    open(path, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    for w, ((h, rms), s) in enumerate(zip(analyse(), waves())):
        print("wave %d %s  harmonic %d  rms %.2f  levels %s" % (w, "".join("%x" % x for x in s), h, rms,
                                                                 LEVELS[w * 16:w * 16 + 16]))
