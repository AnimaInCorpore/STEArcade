"""The STE port's graphics and colours (build/mikie/, ROM-derived: never committed).

    python tools/assets.py

The picture is MAME's ROT270 picture, 224 x 256: picture pixel (X, Y) is the raw pixel (x = 255 - Y, y = X + 16).  The
tiles and sprites are stored turned (numpy rot90: the turned pixel [r][c] is the raw [c][n - 1 - r]), so MAME's flip x
(raw columns) is the picture's flip of the rows, MAME's flip y the picture's flip of the columns.

* mk_tiles.bin: the 512 turned tiles (8 x 8, 4 bpp) unflipped: 8 rows of 4 bytes, two pens a byte (the left pixel in the
  high nibble): 32 bytes a tile.
* mk_spr.bin: the 2 x 256 turned sprites (16 x 16, 4 bpp; code = graphics bank * 256 + code), 16 rows of 8 bytes: 128 a
  sprite.
* mk_assets.s: mk_pal (16 STE colours), mk_tpen / mk_spen (per palette bank 0-7 256 bytes: colour * 16 + pen -> colour
  index; sprite pen 0 is transparent whatever its colour), the sprite shapes' generated code (engine/sprite_programs.py:
  a shape is (code, picture flips), the coverage's; docs/sprite-preparation.md).
* mk_sstream.bin: the end mask streams.

Colours: black and 15 fitted (engine/palette_native.py, docs/colours.md) to the reference pictures' pens of the coverage
runs (ref/cover.py's `pens`), every pen mapped to the nearest.
Current colour default (2026-11-05): engine/palette_native.py; see docs/palette-defaults.md.
"""
from pathlib import Path
import collections
import pickle
import sys
import numpy as np
sys.path[:0] = [str(Path(__file__).resolve().parent), str(Path(__file__).resolve().parents[3] / 'engine')]
from machine import Video
from paths import build_dir
import palette_quantize as PQ
import sprite_programs as sp

BUILD = build_dir('mikie')
CODES = 512                                 # sprite codes (graphics bank * 256 + code: the shape number)
PREFIX = 'mk'
SHARE = 1.0                                 # code for the most drawn shapes up to this share of the draws


def cover_files():
    return sorted(BUILD.glob('cover[0-9]*.pkl'))


def histogram():
    h = collections.Counter()
    for f in cover_files():
        h.update(pickle.loads(f.read_bytes())['pens'])
    return h


def palette(v):
    """-> (16 colours, pen map [4096])"""
    import palette_native as pn
    cols, pairs = pn.prom('mikie', histogram(), v.pens, lambda p: p >= 0x800)
    return [tuple(map(int, c)) for c in cols], pairs >> 4


def nibbles(img):
    out = bytearray()
    for row in img:
        for c in range(0, len(row), 2):
            out.append((int(row[c]) << 4) | int(row[c + 1]))
    return bytes(out)


def turned(g):
    """a graphic [h, w] turned a quarter counter-clockwise (the picture's frame)"""
    return np.rot90(g)


def shape_masks(v, code, fx, fy):
    """the sprite's 16 row masks (bit 15 the leftmost picture pixel) for the picture's flips (fx: the columns reversed,
    fy: the rows); pen 0 is transparent"""
    t = turned(v.sprites[code >> 8][code & 255])
    if fx:
        t = t[:, ::-1]
    if fy:
        t = t[::-1]
    return [sum(1 << (15 - c) for c in range(16) if int(t[r, c]) != 0) for r in range(16)]


def shape_id(code, fx, fy):
    return code << 2 | int(fx) << 1 | int(fy)


def coverage_shapes(share=1.0):
    """the coverage's shapes (code, picture flip x, picture flip y), the most drawn first, up to `share` of the draws.
    The coverage's flips are MAME's: flip x (raw columns) is the picture's rows."""
    seen = collections.Counter()
    for f in cover_files():
        for (code, bank, colour, fx, fy), n in pickle.loads(f.read_bytes())['sprites'].items():
            seen[(bank << 8 | code % 256, bool(fy), bool(fx))] += n
    total, acc, out = sum(seen.values()), 0, []
    for k, n in seen.most_common():
        if share < 1 and acc >= share * total:
            break
        out.append(k)
        acc += n
    return sorted(out), acc / max(total, 1)


def sprite_programs(v):
    keys, got = coverage_shapes(SHARE)
    shapes = {shape_id(code, fx, fy): shape_masks(v, code, fx, fy) for code, fx, fy in keys}
    progs, stream, st = sp.programs(shapes, CODES * 4, table=PREFIX + '_shapes', stream_sym=PREFIX + '_sstream')
    print('generated code: %%(routines)d routines (%%(code_lines)d lines) for %%(shapes)d shapes x 16 shifts x 3 clips '
          '(%.1f%%%% of the draws); stream blocks %%(stream_blocks)d, %%(stream_bytes)d bytes' % (100 * got) % st)
    return progs, stream


def build():
    v = Video()
    cols, pmap = palette(v)
    assert len(v.tiles) == 512 and v.sprites[0].shape[0] == 256
    (BUILD / 'mk_tiles.bin').write_bytes(b''.join(nibbles(turned(v.tiles[c])) for c in range(512)))
    (BUILD / 'mk_spr.bin').write_bytes(b''.join(nibbles(turned(v.sprites[b][c])) for b in (0, 1) for c in range(256)))
    lines = ['; generated by games/mikie/tools/assets.py: the colours and pen maps', '\tsection data,data',
             'mk_pal:\tdc.w ' + ','.join('$%03X' % w for w in PQ.ste_words(np.array(cols))), 'mk_tpen:']
    for base, name in ((0, 'mk_tpen'), (0x800, 'mk_spen')):
        if base:
            lines.append('mk_spen:')
        for bank in range(8):
            row = [int(pmap[base + bank * 256 + i]) for i in range(256)]
            lines += ['\tdc.b ' + ','.join(str(x) for x in row[i:i + 16]) for i in range(0, 256, 16)]
    lines += ['\teven']
    progs, stream = sprite_programs(v)
    lines += progs
    (BUILD / 'mk_sstream.bin').write_bytes(stream)
    (BUILD / 'mk_assets.s').write_text('\n'.join(lines) + '\n')
    (BUILD / 'mk_penmap.bin').write_bytes(bytes(int(x) for x in pmap))
    (BUILD / 'mk_colours.bin').write_bytes(bytes(c for col in cols for c in col))
    err = np.abs(np.array(cols, float)[pmap] - v.pens.astype(float))
    h = histogram()
    w = np.array([h.get(p, 0) for p in range(4096)], float)
    print('colours', cols)
    print('mean error a channel (weighted by pixels): %.1f' % ((err.mean(1) * w).sum() / max(w.sum(), 1)))
    worst = sorted(((err[p].max(), p) for p in range(4096) if w[p] > 0), reverse=True)[:8]
    print('worst pens (max channel error, pen, rgb -> ste):', [(int(e), p, tuple(int(x) for x in v.pens[p]),
                                                               cols[pmap[p]]) for e, p in worst])


if __name__ == '__main__':
    build()
