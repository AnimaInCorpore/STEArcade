"""Dig Dug's assets for the STE: build/digdug/digdug_assets.s (stub: the palette)."""
import os, sys
sys.path[:0] = [os.path.dirname(os.path.abspath(__file__)), os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "engine")]
from paths import build_dir
BUILD = str(build_dir("digdug"))


def build():
    lines = ["; generated by assets.py", "\tsection data,data", "\tcnop 0,2", "dd_palette:", "\tdc.w $000,$FFF,$F00,$0F0,$00F,$FF0,$0FF,$F0F"]
    lines.append("\tdc.w $888,$444,$CCC,$F80,$08F,$80F,$8F0,$F08")
    open(os.path.join(BUILD, "digdug_assets.s"), "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    build()
