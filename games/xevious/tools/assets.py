"""Super Xevious graphics for the STE: build/xevious/xevious_assets.s + binaries.

The arcade raster (288 x 224, x right, y down) is shown rotated 90 degrees clockwise: display x = 223 - raw y, display
y = raw x; 224 pixels wide (GAME_X = 24 bytes of the 320 pixel line), 288 lines.

Palette: 16 STE colours fitted to the master colours the picture shows (ref/pens.py, engine/palette_quantize.py, the
default fitter, flat: one STE index per pen); the same STE index for every use of a master colour.

Graphics in display orientation, as data the renderer converts when it draws (render.s):
  bgt.bin: 512 background tiles x 4 flips (bit 0: raw x flip, bit 1: raw y flip) x 8 display lines x 2 bytes (pen bit 0
           of the 8 pixels, pen bit 1);
  fgt.bin: 512 characters x 4 flips x 8 lines x 1 byte (the pixels that are not pen 0);
  spt.bin: 320 sprite tiles x 4 flips (bit 0: flip x, bit 1: flip y) x 16 lines x 3 words (pen bits 0, 1, 2).
Look-ups to STE indices (255 = transparent): bg_lut (128 colours x 4 pens), spr_lut (64 palettes x 8 pens), fg_lut (64).
"""
import os, pickle, sys, glob
sys.path[:0] = [os.path.dirname(os.path.abspath(__file__)), os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "engine")]
import numpy as np
from collections import Counter
from machine import Gfx
from paths import build_dir
import palette_quantize as pq

BUILD = str(build_dir("xevious"))


def pens_files():
    return sorted(glob.glob(os.path.join(BUILD, "xevious_pens_*.pkl")))


def build_palette(g):
    """-> (palette 16 x 3 (multiples of 17), pmap: master colour 0..128 -> STE index)"""
    rgb = [tuple(int(v) for v in c) for c in g.palette]       # 129: the last is black
    files = pens_files()
    if not files:
        raise SystemExit("assets.py: no pens (python games/xevious/ref/pens.py <seed> <frames>): the palette fit needs them")
    sprites, tiles = Counter(), Counter()
    for f in files:
        d = pickle.load(open(f, "rb"))
        for i in range(129):
            sprites[rgb[i]] += int(d["sprites"][i])
            tiles[rgb[i]] += int(d["tiles"][i])
    inputs = np.array(rgb, int)
    palette, pairs = pq.fit((dict(sprites), dict(tiles)), inputs, count=16, cache=os.path.join(BUILD, "palette_cache"), dither=False)
    pmap = pq.flat_map(palette, inputs)
    pmap[128] = 0
    return palette, [int(v) for v in pmap]


def rot(tile):
    """[raw y][raw x] -> [display line][display x]: line = raw x, x = size - 1 - raw y"""
    return tile.T[:, ::-1]


def flipped(tile, fl):
    if fl & 1:
        tile = tile[:, ::-1]
    if fl & 2:
        tile = tile[::-1, :]
    return tile


def build_tiles(g):
    bgt = bytearray()
    for code in range(512):
        for fl in range(4):
            t = rot(flipped(g.bg[code], fl))
            for line in range(8):
                a = b = 0
                for col in range(8):
                    p = int(t[line, col])
                    a |= (p & 1) << (7 - col)
                    b |= (p >> 1) << (7 - col)
                bgt += bytes([a, b])
    fgt = bytearray()
    for code in range(512):
        for fl in range(4):
            t = rot(flipped(g.chars[code], fl))
            for line in range(8):
                m = 0
                for col in range(8):
                    m |= (1 if t[line, col] else 0) << (7 - col)
                fgt.append(m)
    spt = bytearray()
    for code in range(320):
        for fl in range(4):
            t = rot(flipped(g.sprites[code], fl))
            for line in range(16):
                w = [0, 0, 0]
                for col in range(16):
                    p = int(t[line, col])
                    for k in range(3):
                        w[k] |= ((p >> k) & 1) << (15 - col)
                for k in range(3):
                    spt += w[k].to_bytes(2, "big")
    return bytes(bgt), bytes(fgt), bytes(spt)


def build():
    g = Gfx()
    palette, pmap = build_palette(g)
    bgt, fgt, spt = build_tiles(g)
    for name, data in (("bgt", bgt), ("fgt", fgt), ("spt", spt)):
        with open(os.path.join(BUILD, name + ".bin"), "wb") as f:
            f.write(data)
    bg_lut = bytes(pmap[g.bg_lut[i]] for i in range(512))
    spr_lut = bytes(255 if g.sprite_lut[i] == 0x80 else pmap[g.sprite_lut[i]] for i in range(512))
    fg_lut = bytes(pmap[c] for c in range(64))
    fg_any = bytes(1 if g.chars[c].any() else 0 for c in range(256))
    lines = ["; generated by tools/assets.py", "ga_palette:"]
    words = pq.ste_words(palette)
    lines.append("\tdc.w\t" + ",".join("$%03X" % int(w) for w in words))
    for name, data in (("bg_lut", bg_lut), ("spr_lut", spr_lut), ("fg_lut", fg_lut), ("fg_any", fg_any)):
        lines.append("%s:" % name)
        for i in range(0, len(data), 16):
            lines.append("\tdc.b\t" + ",".join(str(b) for b in data[i:i + 16]))
    lines += ["\teven", "bgt:\tincbin\t\"bgt.bin\"", "fgt:\tincbin\t\"fgt.bin\"", "spt:\tincbin\t\"spt.bin\"", "\teven"]
    open(os.path.join(BUILD, "xevious_assets.s"), "w").write("\n".join(lines) + "\n")
    return palette, pmap


if __name__ == "__main__":
    palette, pmap = build()
    print("palette", [tuple(int(v) for v in c) for c in palette])
