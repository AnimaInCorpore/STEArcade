"""Bubble Bobble renderer assets (build/): bb_tiles.bin (16384 tiles, 8 rows x 4 bytes of pen nibbles, the
left pixel in the high nibble), bb_blank.bin (one bit per tile, set if every pixel is transparent),
bb_penmask.bin (a word per tile: the pens it uses), bb_prom.bin (the 128 bytes of the object shape PROM, a71-25.41 $80-$FF) and bb_tables.s (small tables)."""
import json, os, sys
import numpy as np
sys.path[:0] = [os.path.dirname(os.path.abspath(__file__)), os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "engine")]
from machine import decode_tiles, load

from paths import build_dir


def build():
    t = decode_tiles()                           # [16384][8][8] pens
    packed = (t[:, :, 0::2] << 4) | t[:, :, 1::2]  # [n][8][4]
    b = str(build_dir("bublbobl"))
    os.makedirs(b, exist_ok=True)
    open(os.path.join(b, "bb_tiles.bin"), "wb").write(packed.astype(np.uint8).tobytes())
    blank = (t == 15).all(axis=(1, 2))
    bits = np.zeros(len(t) // 8, np.uint8)
    for i in range(8):
        bits |= (blank[i::8].astype(np.uint8) << i)
    open(os.path.join(b, "bb_blank.bin"), "wb").write(bits.tobytes())      # bit (code & 7) of byte (code >> 3)
    pens = np.zeros(len(t), np.uint16)            # bit p set if the tile has a pixel of pen p (big endian words)
    for p in range(16):
        pens |= ((t == p).any(axis=(1, 2)).astype(np.uint16) << p)
    open(os.path.join(b, "bb_penmask.bin"), "wb").write(pens.astype(">u2").tobytes())
    open(os.path.join(b, "bb_prom.bin"), "wb").write(load("a71-25.41")[0x80:0x100])
    lines = ["; generated by assets.py", "spread:"]
    for i in range(16):                          # plane 0 in the top byte: bit k of i in plane k
        lines.append("\tdc.l\t$%08X" % (((i & 1) << 24) | (((i >> 1) & 1) << 16) | (((i >> 2) & 1) << 8) | ((i >> 3) & 1)))
    lines.append("swapnib:")
    for i in range(0, 256, 16):
        lines.append("\tdc.b\t" + ",".join("$%02X" % (((v & 15) << 4) | (v >> 4)) for v in range(i, i + 16)))
    lines.append("mh_table:")               # the high s bits of every byte
    for s in range(8):
        v = (0xFF << (8 - s)) & 0xFF if s else 0
        lines.append("\tdc.l\t$%08X" % (v * 0x01010101))
    lines.append("ste_nib:")                # 4 bit arcade colour value -> STE nibble (bit 3 = the low bit)
    lines.append("\tdc.b\t" + ",".join("$%02X" % (((v & 1) << 3) | (v >> 1)) for v in range(16)))
    # the fixed palette (render.s STATICPAL, docs/palette_static.json from ref/palette_fit.py): slots 1-15, and every
    # arcade colour (r << 8 | g << 4 | b) -> the slot of its nearest pen colour in Oklab
    sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "ref"))
    from palette_fit import nearest
    pens = [[int(h[i:i + 2], 16) for i in (1, 3, 5)] for h in json.load(open(os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "docs", "palette_static.json")))["pens"]]
    lines.append("STAT_PENS = %d" % len(pens))
    lines.append("stat_pens:")              # slot 0 (the background) and the slots after the pens are set at run time
    lines.append("\tdc.w\t$000," + ",".join("$%X%X%X" % (r // 17, g // 17, b // 17) for r, g, b in pens)
                 + ",$000" * (15 - len(pens)))
    allc = np.array([[k >> 8, (k >> 4) & 15, k & 15] for k in range(4096)]) * 17
    near = nearest(allc, np.array(pens)) + 1
    lines.append("stat_near:")
    for i in range(0, 4096, 32):
        lines.append("\tdc.b\t" + ",".join(str(v) for v in near[i:i + 32]))
    open(os.path.join(b, "bb_tables.s"), "w").write("\n".join(lines) + "\n")
    return len(t), int(blank.sum())


if __name__ == "__main__":
    print("tiles, blank:", build())
