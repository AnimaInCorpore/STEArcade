"""The STE port's graphics and colours (build/junofrst/, ROM-derived: never committed).

    python tools/assets.py

* ste_pal_tab (jf_assets.s): 256 words, a palette RAM byte -> its STE colour.  The game has exactly 16 pens (the 16
  palette RAM bytes the CPU writes) and the STE 16 colours: every pen is an STE index, no fit is needed (the colour
  policy of docs/colours.md, "Exact where it fits"); the arcade's resistor-network colour (machine.pens) is snapped
  to the STE's 4 bits a gun (the `ste_word` of the other ports).  "Bounded colour fit": the fit is bounded at 16
  colours by construction.
* blitrom.bin: the 24 KB blitter ROM (jfs3_c7, jfs4_d7, jfs5_e7) for the runtime's blit.
"""
from pathlib import Path
import sys
import numpy as np
sys.path[:0] = [str(Path(__file__).resolve().parent), str(Path(__file__).resolve().parents[3] / 'engine')]
from machine import pens, load, BLIT
from paths import build_dir


def ste_word(c):
    conv = lambda n: ((n >> 1) & 7) | ((n & 1) << 3)
    r, g, b = (int(v) // 17 for v in c)
    return (conv(r) << 8) | (conv(g) << 4) | conv(b)


def build():
    b = build_dir('junofrst')
    words = [ste_word(pens([v])[0]) for v in range(256)]
    lines = ['; generated by games/junofrst/tools/assets.py', '\teven', 'ste_pal_tab:']
    for i in range(0, 256, 16):
        lines.append('\tdc.w ' + ','.join('$%03X' % w for w in words[i:i + 16]))
    lines += ['jf_blitrom:\tincbin "blitrom.bin"', '\teven']
    (b / 'jf_assets.s').write_text('\n'.join(lines) + '\n')
    (b / 'blitrom.bin').write_bytes(b''.join(load(n) for n in BLIT))
    print('assets: 256 palette bytes, blitter ROM %d bytes' % (0x6000))


if __name__ == '__main__':
    build()
