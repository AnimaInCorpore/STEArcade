"""Static translation of the 1943 i8751 firmware to 68000 code (build/1943/mcu_code.s), the instructions of tools/mcu.py.

The firmware is small: the reset code (0000 -> 0100: clear the RAM, set the ports and interrupt enables, the idle loop
`sjmp $` at 011A) and the INT1 handler (0013 -> 0200: read the command from P0, search the 32 (command, reply) pairs of
the table at 0800, write the reply to P0 and strobe P3 bit 6, reti).  Every instruction becomes 68000 code on the
internal RAM / SFR image (a0 = mcu_ram, a1 = mcu_rom), with the same effects as tools/mcu.py:

* Rn is register bank 0: no reachable instruction sets PSW bits 3-4 (checked here: the only PSW write is `anl PSW,#E7`).
* P0 read = the command AND the port latch; a write to P3 (or a bit of it) whose bit 6 falls copies P0 to the reply
  latch g_mcu_response.
* PSW bit 0 (the parity of ACC, which tools/mcu.py keeps after every instruction) is computed where PSW is read and
  when the code reaches the idle loop.
* reti pops the return address and continues at the idle loop (the only place INT1 interrupts), else it stops.
* ACC is kept in d0 (written back to the RAM where PSW is read and where the run ends); subb takes CY and OV from the
  68000's borrow and overflow, AC from bit 4 of a ^ b ^ result.

    python mcux.py      -> build/1943/mcu_code.s, prints the instructions translated
"""
from pathlib import Path
import sys
sys.path[:0] = [str(Path(__file__).resolve().parent), str(Path(__file__).resolve().parents[3] / 'engine')]
from paths import build_dir

LENGTH = {0x00: 1, 0x02: 3, 0x05: 2, 0x32: 1, 0x53: 3, 0x70: 2, 0x74: 2, 0x75: 3, 0x80: 2, 0x93: 1, 0x9a: 1, 0xc2: 2,
          0xc3: 1, 0xd2: 2, 0xe4: 1, 0xe5: 2, 0xf5: 2}
for _lo, _n in ((0x78, 2), (0x88, 2), (0xa8, 2), (0xd8, 2), (0xe8, 1), (0xf8, 1)):
    for _o in range(_lo, _lo + 8):
        LENGTH[_o] = _n
LENGTH[0xf6] = LENGTH[0xf7] = 1
ENTRIES = (0x0000, 0x0013)
IDLE = 0x011a
P0, PSW, ACC, P3 = 0x80, 0xd0, 0xe0, 0xb0


def rel(pc, n, off):
    return (pc + n + ((off ^ 128) - 128)) & 0xffff


def discover(rom):
    code, work = {}, list(ENTRIES)
    while work:
        pc = work.pop()
        while pc not in code:
            op = rom[pc]
            if op not in LENGTH:
                raise ValueError(f'i8751 opcode {op:02x} at {pc:04x} is not translated')
            n = LENGTH[op]
            code[pc] = bytes(rom[pc:pc + n])
            if op == 0x02:
                pc = rom[pc + 1] * 256 + rom[pc + 2]
                continue
            if op == 0x80:
                t = rel(pc, 2, rom[pc + 1])
                if t == pc:
                    break
                pc = t
                continue
            if op == 0x32:
                break
            if op == 0x70 or 0xd8 <= op <= 0xdf:
                work.append(rel(pc, 2, rom[pc + 1]))
            pc += n
    return code


def bitaddr(bit):
    return (bit & 0xf8, bit & 7) if bit >= 128 else (0x20 + bit // 8, bit & 7)


def emit(rom, code):
    for pc, b in code.items():
        op = b[0]
        writes_psw = (op in (0x75, 0x53, 0x05, 0xf5) and b[1] == PSW) or (0x88 <= op <= 0x8f and b[1] == PSW) or \
                     (op in (0xc2, 0xd2) and bitaddr(b[1]) in ((PSW, 3), (PSW, 4)))
        if writes_psw and not (op == 0x53 and b[2] & 0x18 == 0):
            raise ValueError(f'{pc:04x}: a PSW write that may switch the register bank')
    out = ['; generated by tools/mcux.py: the i8751 firmware (mcu.rom) as 68000 code; a0 = the internal RAM, a1 = the ROM',
           '\tsection text,code']

    def write(addr, src):
        """store the byte src (an operand) to the direct address; P3: the falling edge of bit 6 latches P0"""
        if addr == P3:
            out.extend([f'\tmove.b {src},d2', '\tbsr mcu_p3'])
        elif addr == ACC:
            out.append(f'\tmove.b {src},d0')
        else:
            out.append(f'\tmove.b {src},{addr}(a0)')

    def read(addr, dst):
        if addr == P0:
            out.extend([f'\tmove.b mcu_command,{dst}', f'\tand.b {P0}(a0),{dst}'])
        elif addr == PSW:
            out.extend([f'\tmove.b d0,{ACC}(a0)', '\tbsr mcu_parity', f'\tmove.b {PSW}(a0),{dst}'])
        elif addr == ACC:
            out.append(f'\tmove.b d0,{dst}')
        else:
            out.append(f'\tmove.b {addr}(a0),{dst}')

    for pc in sorted(code):
        b = code[pc]
        op = b[0]
        out.append(f'M{pc:04X}:\t\t; {b.hex()}')
        if op == 0x00:
            pass
        elif op == 0x02:
            out.append(f'\tbra M{b[1] * 256 + b[2]:04X}')
        elif op == 0x75:
            write(b[1], f'#${b[2]:02x}')
        elif 0x78 <= op <= 0x7f:
            out.append(f'\tmove.b #${b[1]:02x},{op & 7}(a0)')
        elif op == 0x74:
            out.append(f'\tmove.b #${b[1]:02x},d0')
        elif op in (0xf6, 0xf7):
            out.extend(['\tmoveq #0,d1', f'\tmove.b {op & 1}(a0),d1', '\tmove.b d0,(a0,d1.w)'])
        elif op == 0xf5:
            write(b[1], 'd0')
        elif op == 0xe4:
            out.append('\tmoveq #0,d0')
        elif 0xe8 <= op <= 0xef:
            out.append(f'\tmove.b {op & 7}(a0),d0')
        elif 0xf8 <= op <= 0xff:
            out.append(f'\tmove.b d0,{op & 7}(a0)')
        elif op == 0xe5:
            read(b[1], 'd0')
        elif 0xa8 <= op <= 0xaf:
            read(b[1], 'd1')
            out.append(f'\tmove.b d1,{op & 7}(a0)')
        elif 0x88 <= op <= 0x8f:
            write(b[1], f'{op & 7}(a0)')
        elif op in (0xc2, 0xd2):
            addr, bit = bitaddr(b[1])
            if addr == PSW:
                out.extend([f'\tmove.b d0,{ACC}(a0)', '\tbsr mcu_parity'])
            if addr == P3:
                out.extend([f'\tmove.b {P3}(a0),d2', f'\t{"bclr" if op == 0xc2 else "bset"} #{bit},d2', '\tbsr mcu_p3'])
            else:
                out.append(f'\t{"bclr" if op == 0xc2 else "bset"} #{bit},{addr}(a0)')
        elif op == 0x53:
            if b[1] == P3:
                out.extend([f'\tmove.b {P3}(a0),d2', f'\tand.b #${b[2]:02x},d2', '\tbsr mcu_p3'])
            else:
                out.append(f'\tand.b #${b[2]:02x},{b[1]}(a0)')
        elif op == 0xc3:
            out.append(f'\tbclr #7,{PSW}(a0)')
        elif op == 0x05:
            if b[1] == P3:
                out.extend([f'\tmove.b {P3}(a0),d2', '\taddq.b #1,d2', '\tbsr mcu_p3'])
            else:
                out.append(f'\taddq.b #1,{b[1]}(a0)')
        elif op == 0x93:
            out.extend(['\tmoveq #0,d1', '\tmove.b $83(a0),d1', '\tlsl.w #8,d1', '\tmove.b $82(a0),d1',
                        '\tmoveq #0,d2', '\tmove.b d0,d2', '\tadd.l d2,d1', '\tmove.b (a1,d1.l),d0'])
        elif op == 0x9a:
            # A = A - R2 - CY: CY = the 68000's borrow, OV its overflow, AC = bit 4 of a ^ b ^ result
            def skip_set(bit, flag):
                out.extend([f'\tbtst #{bit},d5', f'\tbeq.s .s{pc:04x}_{flag}', f'\tbset #{flag},d7', f'.s{pc:04x}_{flag}:'])
            out.extend(['\tmove.b 2(a0),d2', f'\tmove.b {PSW}(a0),d7', '\tmove.b d7,d5', '\tadd.b d5,d5',
                        '\tmove.b d0,d1', '\tsubx.b d2,d1', '\tmove sr,d5', '\tand.b #$3b,d7'])
            skip_set(0, 7)
            skip_set(1, 2)
            out.extend(['\teor.b d1,d2', '\teor.b d0,d2', '\tmove.b d2,d5'])
            skip_set(4, 6)
            out.extend([f'\tmove.b d7,{PSW}(a0)', '\tmove.b d1,d0'])
        elif op == 0x70:
            out.extend(['\ttst.b d0', f'\tbne M{rel(pc, 2, b[1]):04X}'])
        elif 0xd8 <= op <= 0xdf:
            out.extend([f'\tsubq.b #1,{op & 7}(a0)', f'\tbne M{rel(pc, 2, b[1]):04X}'])
        elif op == 0x80:
            t = rel(pc, 2, b[1])
            if t == pc:
                out.extend([f'\tmove.w #${pc:04x},mcu_pc', f'\tmove.b d0,{ACC}(a0)', '\tbra mcu_parity'])  # (the idle loop: the run ends)
            else:
                out.append(f'\tbra M{t:04X}')
        elif op == 0x32:
            out.extend(['\tbsr mcu_reti', f'\tcmp.w #${IDLE:04x},d1', f'\tbeq M{IDLE:04X}', '\tmove.l d1,d7',
                        '\tjmp z80_unsupported'])
        else:
            raise ValueError(f'{pc:04x}: {b.hex()}')
    return '\n'.join(out) + '\n'


def generate():
    rom = (build_dir('1943') / 'mcu.rom').read_bytes()
    code = discover(rom)
    if IDLE not in code:
        raise ValueError('no idle loop')
    return emit(rom, code), len(code)


if __name__ == '__main__':
    text, n = generate()
    (build_dir('1943') / 'mcu_code.s').write_text(text)
    print(n, 'i8751 instructions translated')
