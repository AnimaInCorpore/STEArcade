"""The sound assets of build/yiear/: snd_data.s (the YM's tables, the VLM5030 phrases' place in snd_pcm) and snd_pcm.bin
(the phrases rendered by engine/vlm5030.py, 12517 Hz, 8 bits signed, mono, for the DMA sound).

    python tools/sndgen.py
"""
import sys
from pathlib import Path

import numpy as np

sys.path[:0] = [str(Path(__file__).resolve().parent), str(Path(__file__).resolve().parents[3] / 'engine')]
from paths import build_dir
from machine import load
import sound as S
import vlm5030
import vlm_frames

BUILD = build_dir('yiear')
DMA_HZ = 12517
MIN_SAMPLES = 3 * 135                     # (a phrase shorter than three arcade frames is no speech)


def used():
    """the phrases the coverage runs started (ref/cover.py's `phrases`)"""
    import collections
    import pickle
    c = collections.Counter()
    for f in sorted(BUILD.glob('cover[0-9]*.pkl')):
        c.update(pickle.loads(f.read_bytes()).get('phrases', {}))
    return sorted(c) or list(range(256))


def phrases():
    """-> {data byte: samples at 12517 Hz as int8 bytes}: the phrases the game starts (speech parameter 0)"""
    rom = load('407_c09.8b')
    frames = vlm_frames.frames()
    out = {}
    for d in used():
        if frames[d] <= 3:
            continue
        samples, n = vlm5030.phrase(rom, d, 0, limit=400000)
        if n < MIN_SAMPLES:
            continue
        x = np.array(samples, float)
        m = int(len(x) * DMA_HZ / vlm5030.RATE)
        pos = np.arange(m) * vlm5030.RATE / DMA_HZ
        y = np.interp(pos, np.arange(len(x)), x)
        out[d] = np.clip(np.round(y / 4), -128, 127).astype(np.int8).tobytes()
    return out


def build():
    ph = phrases()
    blob = bytearray()
    index = {}
    for d, b in ph.items():
        index[d] = (len(blob), len(b))
        blob += b
        blob += bytes(len(blob) & 1)
    (BUILD / 'snd_pcm.bin').write_bytes(bytes(blob) + bytes(4))
    lines = ['; generated by games/yiear/tools/sndgen.py: the YM2149 tables and the VLM5030 phrases', '\tsection data,data', '\teven',
             'snd_ptab:\t; SN tone period -> YM period']
    vals = [S.ym_period(n) for n in range(1024)]
    for i in range(0, 1024, 16):
        lines.append('\tdc.w ' + ','.join('%d' % v for v in vals[i:i + 16]))
    lines.append('snd_ntab:\t; tone 2 period & 15 -> the YM noise period (noise mode 3, period < 16)')
    lines.append('\tdc.b ' + ','.join('%d' % S.ym_noise(3, n) for n in range(16)))
    lines.append('snd_vtab:\tdc.b ' + ','.join(map(str, S.VTAB)))
    lines.append('\teven')
    lines.append('snd_phr_tab:\t; VLM data byte -> its samples (offset in snd_pcm, length; 0: none)')
    for d in range(256):
        o, n = index.get(d, (0, 0))
        lines.append('\tdc.l %d,%d' % (o, n))
    (BUILD / 'snd_data.s').write_text('\n'.join(lines) + '\n')
    print('phrases %d, %d bytes of samples; data bytes %s' % (len(ph), len(blob), sorted(ph)))


if __name__ == '__main__':
    build()
