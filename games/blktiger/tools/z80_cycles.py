IRQ_IM1 = CC_OP[0xff] + CC_EX[0xff]


def cycles(code):
    """code: the instruction's bytes (prefixes included)."""
    op = code[0]
    if op == 0xcb:
        return CC_CB[code[1]], 0
    if op == 0xed:
        return CC_ED[code[1]], CC_EX[code[1]]
    if op in (0xdd, 0xfd):
        if code[1] == 0xcb:
            return CC_XYCB[code[3]], 0
        return CC_XY[code[1]], CC_EX[code[1]]
    return CC_OP[op], CC_EX[op]
